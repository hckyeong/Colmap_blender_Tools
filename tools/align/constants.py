MARKER_GENERATED_HUE_OFFSET = 0.43
MARKER_GENERATED_HUE_STEP = 0.618033988749895
MARKER_GENERATED_SATURATION = 0.82
MARKER_GENERATED_VALUE = 1.0


def marker_pair_color(pair_id: int) -> tuple[float, float, float, float]:
    """안정적인 pair_id에 대응하는 고유 마커 쌍 색상을 반환합니다."""
    if pair_id < 1:
        raise ValueError("마커 쌍 ID는 1 이상이어야 합니다.")
    palette_index = pair_id - 1
    if palette_index < len(MARKER_PALETTE):
        return MARKER_PALETTE[palette_index]

    # 고정 팔레트 이후에도 삭제·Undo와 무관하게 같은 ID는 같은 색을 사용합니다.
    generated_index = palette_index - len(MARKER_PALETTE)
    hue = (MARKER_GENERATED_HUE_OFFSET + generated_index * MARKER_GENERATED_HUE_STEP) % 1.0
    red, green, blue = hsv_to_rgb(
        hue,
        MARKER_GENERATED_SATURATION,
        MARKER_GENERATED_VALUE,
    )
    return red, green, blue, 1.0
