def __getattr__(name: str):
    """model repository 순환을 피하면서 요청된 ICP runtime 공개 심볼만 지연 반환합니다."""

    if name not in _ICP_RUNTIME_PUBLIC:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    from . import icp_runtime

    return getattr(icp_runtime, name)


